/**
 * The glyphs that only ever mean "working". Wherever one is drawn — a status tile, a button, a card, a table row — it
 * turns (`hui-icon--spin`), so no caller has to ask for the turn; the stylesheet holds it still for a person who asks
 * the browser for reduced motion.
 */
const TURNING: Readonly<Partial<Record<IconName, true>>> = {
    progress_activity: true,
};

/** The glyph drawn for a name the set does not hold. */
export const FALLBACK_ICON: IconName = 'tune';

/** Whether the set holds a glyph of this name. */
export function isIconName(name: string): name is IconName {
    return Object.hasOwn(GLYPHS, name);
}

/** Every glyph name the set holds, in alphabetical order. */
export const ICON_NAMES: readonly IconName[] = Object.freeze(Object.keys(GLYPHS).filter(isIconName));

/** The glyph for a run-time name, or `fallback` when the set does not hold it. */
export function iconOr(name: string | undefined, fallback: IconName = FALLBACK_ICON): IconName {
    return name !== undefined && isIconName(name) ? name : fallback;
}

/** Rendered sizes in pixels; each has its own class in the admin UI kit's stylesheet. */
export type IconSize = 14 | 16 | 18 | 20 | 22 | 24 | 26 | 28 | 30;

export interface IconProps {
    /** A glyph of the set; any other name draws the fallback glyph. */
    readonly name: string;
    readonly size?: IconSize | undefined;
    /** The filled variant, where the glyph has one. */
    readonly filled?: boolean | undefined;
    /** Announces the glyph as an image with this text; left out, the glyph is decorative. */
    readonly label?: string | undefined;
    readonly class?: string | undefined;
}

export function Icon({ name, size = 18, filled = false, label, class: extra }: IconProps): JSX.Element {
    const glyph = iconOr(name);
    const path = (filled ? FILLED[glyph] : undefined) ?? GLYPHS[glyph];
    const spin = TURNING[glyph] === true ? 'hui-icon--spin' : undefined;
    const className = ['hui-icon', `hui-icon--${size}`, spin, extra].filter((part) => part !== undefined).join(' ');
    const decorative = label === undefined;
    return (
        <svg
            class={className}
            viewBox="0 -960 960 960"
            focusable="false"
            aria-hidden={decorative ? true : undefined}
            role={decorative ? undefined : 'img'}
            aria-label={label}
        >
            <path d={path} />
        </svg>
    );
}
